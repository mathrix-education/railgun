<?php

declare(strict_types=1);

namespace Tests\Functional\Support;

use Railgun\Support\LazyStdClass;
use Tests\ApplicationTestCase;

/**
 * @coversDefaultClass \Railgun\Support\LazyStdClass
 */
class LazyStdClassTest extends ApplicationTestCase
{
    private LazyStdClass $instance;

    public function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub

        $this->instance = new LazyStdClass();
    }

    /**
     * @covers ::__construct
     */
    public function testConstruct(): void
    {
        $instance = new LazyStdClass(['a' => 12, 'b' => (static fn() => 15)]);
        $this->assertEquals(12, $instance->a);
        $this->assertEquals(15, $instance->b);
    }

    /**
     * @covers ::__isset
     * @covers ::__get
     * @covers ::__set
     */
    public function testMagic(): void
    {
        $this->instance->a = 12;
        $this->instance->b = static fn() => 15;

        $this->assertFalse(isset($this->instance->c));
        $this->assertEquals(12, $this->instance->a);
        $this->assertEquals(15, $this->instance->b);
    }

    /**
     * @covers ::offsetGet
     * @covers ::offsetSet
     * @covers ::offsetUnset
     * @covers ::offsetExists
     * @covers ::next
     * @covers ::key
     * @covers ::current
     * @covers ::rewind
     * @covers ::valid
     * @covers ::toArray
     */
    public function testArrayable(): void
    {
        $this->instance['a'] = 12;
        $this->instance['b'] = static fn() => 15;
        $this->instance['c'] = static fn() => 18;
        unset($this->instance['c']);

        $this->assertFalse(isset($this->instance['c']));
        $this->assertEquals(12, $this->instance['a']);
        $this->assertEquals(15, $this->instance['b']);
        $this->assertNull($this->instance['c']);
        $this->assertEquals(['a' => 12, 'b' => 15], $this->instance->toArray());
    }
}
